export const FORMAT_COLORS = {
  0: 0x000000, 1: 0x0000aa, 2: 0x00aa00, 3: 0x00aaaa, 4: 0xaa0000, 5: 0xaa00aa, 6: 0xffaa00, 7: 0xaaaaaa,
  8: 0x555555, 9: 0x5555ff, a: 0x55ff55, b: 0x55ffff, c: 0xff5555, d: 0xff55ff, e: 0xffff55, f: 0xffffff,
};

export class Font {
  constructor() {
    this.chars = Object.keys(G);
    this.glyph = new Map();
    const cols = 16;
    const rows = Math.ceil(this.chars.length / cols);
    const c = document.createElement('canvas');
    c.width = cols * 8; c.height = rows * 9;
    const g = c.getContext('2d');
    g.fillStyle = '#fff';
    this.chars.forEach((ch, i) => {
      const rowsData = G[ch];
      const w = Math.max(...rowsData.map((r) => r.length));
      const ox = (i % cols) * 8, oy = Math.floor(i / cols) * 9;
      rowsData.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') g.fillRect(ox + x, oy + y, 1, 1); });
      this.glyph.set(ch, { x: ox, y: oy, w });
    });
    this.white = c;
    this.colored = new Map();
    this.unknown = { x: 0, y: 0, w: 5, missing: true };
  }
  sheet(color) {
    let s = this.colored.get(color);
    if (s) return s;
    const c = document.createElement('canvas');
    c.width = this.white.width; c.height = this.white.height;
    const g = c.getContext('2d');
    g.drawImage(this.white, 0, 0);
    g.globalCompositeOperation = 'source-in';
    g.fillStyle = '#' + (color & 0xffffff).toString(16).padStart(6, '0');
    g.fillRect(0, 0, c.width, c.height);
    this.colored.set(color, c);
    return c;
  }
  charWidth(ch) {
    const g = this.glyph.get(ch);
    return (g ? g.w : 5) + 1;
  }
  // width in GUI pixels (ignores formatting codes)
  width(text) {
    let w = 0, bold = false;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (ch === '§' && i + 1 < text.length) { const c = text[i + 1].toLowerCase(); if (c === 'l') bold = true; else if (c === 'r' || FORMAT_COLORS[c] !== undefined) bold = false; i++; continue; }
      w += this.charWidth(ch) + (bold ? 1 : 0);
    }
    return w;
  }
  // draw text; ctx must already be scaled to GUI pixels
  draw(ctx, text, x, y, color = 0xffffff, shadow = true, alpha = 1) {
    text = String(text);
    if (shadow) this._draw(ctx, text, x + 1, y + 1, color, true, alpha);
    return this._draw(ctx, text, x, y, color, false, alpha);
  }
  _draw(ctx, text, x, y, color, isShadow, alpha) {
    let cx = x;
    let col = color, bold = false, strike = false, under = false;
    const prevA = ctx.globalAlpha;
    ctx.globalAlpha = prevA * alpha;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (ch === '§' && i + 1 < text.length) {
        const c = text[i + 1].toLowerCase();
        if (FORMAT_COLORS[c] !== undefined) { col = FORMAT_COLORS[c]; bold = false; strike = false; under = false; }
        else if (c === 'l') bold = true;
        else if (c === 'm') strike = true;
        else if (c === 'n') under = true;
        else if (c === 'r') { col = color; bold = false; strike = false; under = false; }
        i++;
        continue;
      }
      const g = this.glyph.get(ch) || this.unknown;
      const drawCol = isShadow ? shadowOf(col) : col;
      if (ch !== ' ') {
        if (g.missing) { ctx.fillStyle = hex(drawCol); ctx.fillRect(cx, y, 5, 7); }
        else {
          const sheet = this.sheet(drawCol);
          ctx.drawImage(sheet, g.x, g.y, g.w, 8, cx, y, g.w, 8);
          if (bold) ctx.drawImage(sheet, g.x, g.y, g.w, 8, cx + 1, y, g.w, 8);
        }
      }
      const adv = g.w + 1 + (bold ? 1 : 0);
      if (strike) { ctx.fillStyle = hex(drawCol); ctx.fillRect(cx, y + 3, adv, 1); }
      if (under) { ctx.fillStyle = hex(drawCol); ctx.fillRect(cx, y + 8, adv, 1); }
      cx += adv;
    }
    ctx.globalAlpha = prevA;
    return cx - x;
  }
  drawCentered(ctx, text, cx, y, color = 0xffffff, shadow = true) {
    this.draw(ctx, text, Math.round(cx - this.width(text) / 2), y, color, shadow);
  }
  // split into lines that fit maxWidth
  wrap(text, maxWidth) {
    const out = [];
    for (const para of String(text).split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const w of words) {
        const t = line ? line + ' ' + w : w;
        if (this.width(t) > maxWidth && line) { out.push(line); line = w; }
        else line = t;
      }
      out.push(line);
    }
    return out;
  }
}

export function shadowOf(c) { return ((c & 0xfcfcfc) >> 2) & 0xffffff; }
export function hex(c) { return '#' + (c & 0xffffff).toString(16).padStart(6, '0'); }
